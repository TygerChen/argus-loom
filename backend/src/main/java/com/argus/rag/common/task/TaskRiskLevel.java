package com.argus.rag.common.task;

/**
 * 任务风险级别 —— 入口给请求打的风险标签（只标记，不裁决）。
 * <p>设计边界（用户入口总规则 4）：删除/导出/批量修改/分享/推送类请求
 * <b>在入口就标高风险，后续不得自动直接执行</b>——但"不得自动执行"的拦截
 * 发生在运行器的确认门，入口的职责只是让下游（模型/运行器/工具层）
 * 在看到任何业务逻辑之前就知道"这不是普通只读请求"。</p>
 */
public enum TaskRiskLevel {

    /** 普通只读问答/查询 */
    LOW,

    /**
     * 写知识库（文档上传）：改变知识库内容但非破坏性——现行产品是
     * "全部完成即原子发布、无需人工审核"；文档方案的 pending_review 审核位
     * 属可选演进，落地时把上传升为 HIGH 即可。
     */
    MEDIUM,

    /** 涉及敏感数据导出、删除、外发、批量变更的高风险请求 */
    HIGH
}
